#!/usr/bin/env python3
"""Generate the standalone Challenge from the maintained Mathlib-only statement."""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
THEOREM = """
universe u

/-- **Theorem A** (Theorem 4.4). For a subcategory `Z` of `mod Λ`, `Λ` a
finite-dimensional algebra over a field, the following are equivalent: `Z` is
image-closed; `Z = Gen Z ∩ Cogen Z`; `Z = T ∩ F` for a pretorsion theory
`(T, F)`. -/
theorem PretorsionImageClosed.Challenge.theoremA : PretorsionImageClosed.Statement.TheoremA.{u} := by
  sorry

/-- **Theorem 3.6.** The pretorsion theories of `mod Λ` form a complete lattice,
with meets (3.2), joins (3.3), least element `(0, mod Λ)` and greatest element
`(mod Λ, 0)`. -/
theorem PretorsionImageClosed.Challenge.completeLattice :
    PretorsionImageClosed.Statement.CompleteLattice.{u} := by
  sorry

/-- **Theorem 7.5.** For the linearly oriented quiver `1 → ⋯ → n`, `PT(Λ_n)` is
finite and `∑ x^{ρ_n(T)} q^{|ind(T ∩ F)|} = B_{n+1}(x, q)`. -/
theorem PretorsionImageClosed.Challenge.gandhiPretorsion :
    PretorsionImageClosed.Statement.GandhiPretorsion.{u} := by
  sorry

/-- **Theorem 8.5.** `L_im(Λ_n)` is finite and
`∑ x^{ρ_n(C)} q^{|ind C|} = C_{n+1}(x, q)`. -/
theorem PretorsionImageClosed.Challenge.gandhiImageClosed :
    PretorsionImageClosed.Statement.GandhiImageClosed.{u} := by
  sorry

/-- **Theorem B**, first identity: `∑_{(T,F) ∈ PT(Λ_n)} q^{|ind(T ∩ F)|} = B_{n+1}(1, q)`. -/
theorem PretorsionImageClosed.Challenge.theoremBPretorsion :
    PretorsionImageClosed.Statement.TheoremBPretorsion.{u} := by
  sorry

/-- **Theorem B**, second identity: `∑_{C ∈ L_im(Λ_n)} q^{|ind C|} = C_{n+1}(1, q)`. -/
theorem PretorsionImageClosed.Challenge.theoremBImageClosed :
    PretorsionImageClosed.Statement.TheoremBImageClosed.{u} := by
  sorry
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if Challenge.lean is stale")
    args = parser.parse_args()
    source = (ROOT / "PretorsionImageClosed/Statement.lean").read_text()
    imports = [line.split()[-1] for line in source.splitlines()
               if line.startswith(("import ", "public import "))]
    if not imports or any(name != "Mathlib" and not name.startswith("Mathlib.") for name in imports):
        raise SystemExit("Statement.lean must import only Mathlib")
    expected = "-- Generated by scripts/generate_challenge.py; edit Statement.lean.\n" + source + THEOREM
    target = ROOT / "Challenge.lean"
    if args.check:
        if not target.exists() or target.read_text() != expected:
            raise SystemExit("Challenge.lean is stale; run scripts/generate_challenge.py")
    else:
        target.write_text(expected)
    print(f"Challenge.lean: {len(expected.splitlines())} lines, {len(expected.encode())} bytes")


if __name__ == "__main__":
    main()
